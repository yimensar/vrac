package engine

// This reproducible background scenario deliberately lives beside the engine:
// fixtures must never teach a client to bypass its SQL boundary.
import (
	"database/sql"
	"fmt"
	"sort"
	"time"
)

type Measurement struct {
	Operation string  `json:"operation"`
	P95MS     float64 `json:"p95_ms"`
	BudgetMS  float64 `json:"budget_ms"`
	Passed    bool    `json:"passed"`
}
type PerformanceReport struct {
	NodeCount    int64         `json:"node_count"`
	Iterations   int           `json:"iterations"`
	Measurements []Measurement `json:"measurements"`
	Passed       bool          `json:"passed"`
}

// RunPerformanceScenario requires a new database and generates canonical,
// file-backed data under the same FULL durability settings as normal work.
func RunPerformanceScenario(database string, count, iterations int, progress func(int)) (PerformanceReport, error) {
	return runPerformance(database, count, iterations, progress, false)
}

// MeasurePerformanceScenario explicitly reuses a fixture generated by this
// scenario. Measurements mutate fixture notes; never use production data.
func MeasurePerformanceScenario(database string, iterations int) (PerformanceReport, error) {
	return runPerformance(database, 0, iterations, nil, true)
}
func runPerformance(database string, count, iterations int, progress func(int), reuse bool) (PerformanceReport, error) {
	report := PerformanceReport{Iterations: iterations, Measurements: []Measurement{}, Passed: true}
	if (!reuse && count < 10000) || iterations < 20 {
		return report, fmt.Errorf("scenario requires at least 10000 nodes and 20 iterations")
	}
	e, err := Open(database)
	if err != nil {
		return report, err
	}
	defer e.Close()
	var existing int64
	if err = e.db.QueryRow("SELECT count(*) FROM nodes").Scan(&existing); err != nil {
		return report, err
	}
	var project, deep, sparse Node
	var plain, rich []Node
	if reuse {
		roles := []struct {
			tag         string
			destination *Node
		}{{"perf-project", &project}, {"perf-plain", new(Node)}, {"perf-rich", new(Node)}, {"perf-deep", &deep}, {"perf-sparse", &sparse}}
		for _, role := range roles {
			var id string
			if err = e.db.QueryRow("SELECT node_id FROM node_tags WHERE tag=?", role.tag).Scan(&id); err != nil {
				return report, fmt.Errorf("missing benchmark role %s: %w", role.tag, err)
			}
			*role.destination, err = e.Get(id)
			if err != nil {
				return report, err
			}
		}
		plain = []Node{*roles[1].destination}
		rich = []Node{*roles[2].destination}
	} else {
		if existing != 1 {
			return report, fmt.Errorf("performance scenario requires a fresh database; use -reuse only for an existing generated fixture")
		}
		project, err = e.Create(CreateInput{Text: "Benchmark project", Tags: []string{"project", "perf-project"}})
		if err != nil {
			return report, err
		}
		sparse, err = e.Create(CreateInput{Text: "Sparse project", Tags: []string{"perf-sparse"}})
		if err != nil {
			return report, err
		}
		if _, err = e.Capture("2026-11-01", []CreateInput{{Text: "Sparse mention [[" + sparse.ID + "]]"}}, ""); err != nil {
			return report, err
		}
		plain, err = e.Capture("2026-11-02", []CreateInput{{Text: "Plain page", Tags: []string{"perf-plain"}}}, "")
		if err != nil {
			return report, err
		}
		richInputs := []CreateInput{}
		for i := 0; i < 100; i++ {
			richInputs = append(richInputs, CreateInput{Text: fmt.Sprintf("Decision %03d for [[%s]]", i, project.ID), Tags: []string{"decision", "benchmark", "active"}})
		}
		rich, err = e.Capture("2026-11-02", []CreateInput{{Text: "Meeting [[" + project.ID + "]]", Tags: []string{"meeting", "perf-rich"}, Children: richInputs}}, "")
		if err != nil {
			return report, err
		}
		for i := 0; i < 100; i++ {
			if _, err = e.Create(CreateInput{ParentID: plain[0].ID, Text: fmt.Sprintf("Plain child %d", i)}); err != nil {
				return report, err
			}
		}
		deep = plain[0]
		for i := 0; i < 102; i++ {
			tags := []string{}
			if i == 101 {
				tags = []string{"perf-deep"}
			}
			deep, err = e.Create(CreateInput{ParentID: deep.ID, Text: fmt.Sprintf("Path depth %d", i), Tags: tags})
			if err != nil {
				return report, err
			}
		}
		start := time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)
		const batch = 5000
		for offset := 0; offset < count; offset += batch {
			size := batch
			if count-offset < size {
				size = count - offset
			}
			group := offset / batch
			text := fmt.Sprintf("Historical meeting %04d", group)
			if group%100 == 0 {
				text += " [[" + project.ID + "]]"
			}
			roots, err := e.Capture(start.AddDate(0, 0, group*2).Format("2006-01-02"), []CreateInput{{Text: text, Tags: []string{"meeting"}}}, "")
			if err != nil {
				return report, err
			}
			err = e.mutate("generate-performance-batch", "", nil, nil, func(tx *sql.Tx) error {
				at := "2026-01-01T00:00:00Z"
				_, err := tx.Exec(`WITH RECURSIVE sequence(i) AS (VALUES(1) UNION ALL SELECT i+1 FROM sequence WHERE i<?) INSERT INTO nodes(id,parent_id,position,text,revision,created_at,updated_at) SELECT printf('%032x',i+?),?,i*1024,printf('Archive note %d external account procedure',i+?),1,?,? FROM sequence`, size, offset, roots[0].ID, offset, at, at)
				if err != nil {
					return err
				}
				first, last := fmt.Sprintf("%032x", offset+1), fmt.Sprintf("%032x", offset+size)
				_, err = tx.Exec("INSERT INTO node_tags(node_id,tag) VALUES(?,?)", last, "historical-decision")
				if err != nil {
					return err
				}
				_, err = tx.Exec(`INSERT INTO revisions(node_id,revision,at,summary,snapshot) SELECT id,1,updated_at,'Generated benchmark node',json_object('id',id,'parent_id',parent_id,'text',text,'tags',CASE WHEN id=? THEN json('["historical-decision"]') ELSE json('[]') END,'references',json('[]'),'revision',1,'created_at',created_at,'updated_at',updated_at,'has_children',json('false')) FROM nodes WHERE id>=? AND id<=?`, last, first, last)
				return err
			})
			if err != nil {
				return report, err
			}
			if progress != nil {
				progress(offset + size)
			}
		}
	}
	if !reuse {
		if _, err = e.db.Exec("ANALYZE"); err != nil {
			return report, err
		}
	}
	richPage, err := e.Children(rich[0].ID, "", 100)
	if err != nil {
		return report, err
	}
	editable := richPage.Nodes[0]
	moving := richPage.Nodes[1]
	measure := func(name string, operation func(int) error) error {
		timings := make([]time.Duration, iterations)
		for i := 0; i < iterations; i++ {
			begin := time.Now()
			if err := operation(i); err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
			timings[i] = time.Since(begin)
		}
		sort.Slice(timings, func(i, j int) bool { return timings[i] < timings[j] })
		p95 := float64(timings[(iterations*95+99)/100-1]) / float64(time.Millisecond)
		m := Measurement{Operation: name, P95MS: p95, BudgetMS: 2, Passed: p95 <= 2}
		report.Measurements = append(report.Measurements, m)
		report.Passed = report.Passed && m.Passed
		return nil
	}
	operations := []struct {
		name string
		fn   func(int) error
	}{
		{"plain_page_100", func(int) error { _, err := e.Children(plain[0].ID, "", 100); return err }},
		{"metadata_page_100", func(int) error { _, err := e.Children(rich[0].ID, "", 100); return err }},
		{"read_node", func(int) error { _, err := e.Get(editable.ID); return err }},
		{"path_depth_104", func(int) error { _, err := e.Path(deep.ID); return err }},
		{"create_node", func(i int) error {
			_, err := e.Create(CreateInput{ParentID: plain[0].ID, Text: fmt.Sprintf("Created note %d", i)})
			return err
		}},
		{"edit_content", func(i int) error {
			var err error
			editable, err = e.Update(editable.ID, UpdateInput{Text: fmt.Sprintf("Edited decision %d [[%s]]", i, project.ID), ExpectedRevision: editable.Revision, JournalDate: "2026-11-02"})
			return err
		}},
		{"replace_tags", func(i int) error {
			var err error
			editable, err = e.Update(editable.ID, UpdateInput{Text: editable.Text, Tags: []string{"decision", fmt.Sprintf("tag-%d", i%2)}, ExpectedRevision: editable.Revision, JournalDate: "2026-11-02"})
			return err
		}},
		{"rename_reference_target", func(i int) error {
			var err error
			project, err = e.Update(project.ID, UpdateInput{Text: fmt.Sprintf("Benchmark project %d", i), ExpectedRevision: project.Revision, JournalDate: "2026-11-02"})
			return err
		}},
		{"move_sibling", func(int) error {
			var err error
			moving, err = e.Move(moving.ID, MoveInput{ParentID: rich[0].ID, Placement: Placement{First: true}, ExpectedRevision: moving.Revision, JournalDate: "2026-11-02"})
			return err
		}},
		{"search_text", func(int) error { _, err := e.Search(SearchFilters{Query: "Edited decision", Limit: 10}); return err }},
		{"project_decisions", func(int) error {
			_, err := e.Search(SearchFilters{Tag: "decision", SubjectID: project.ID, Limit: 10})
			return err
		}},
		{"large_project_rare_tag", func(int) error {
			_, err := e.Search(SearchFilters{Tag: "historical-decision", SubjectID: project.ID, Limit: 10})
			return err
		}},
		{"journal_decisions", func(int) error {
			_, err := e.Search(SearchFilters{Tag: "decision", From: "2026-11-02", To: "2026-11-02", Limit: 10})
			return err
		}},
		{"large_project_common_tag", func(int) error {
			_, err := e.Search(SearchFilters{Tag: "meeting", SubjectID: project.ID, Limit: 10})
			return err
		}},
		{"project_browse", func(int) error { _, err := e.Search(SearchFilters{SubjectID: project.ID, Limit: 10}); return err }},
		{"sparse_project_browse", func(int) error { _, err := e.Search(SearchFilters{SubjectID: sparse.ID, Limit: 10}); return err }},
	}
	for _, op := range operations {
		if err = measure(op.name, op.fn); err != nil {
			return report, err
		}
	}
	if err = e.db.QueryRow("SELECT count(*) FROM nodes").Scan(&report.NodeCount); err != nil {
		return report, err
	}
	return report, nil
}
